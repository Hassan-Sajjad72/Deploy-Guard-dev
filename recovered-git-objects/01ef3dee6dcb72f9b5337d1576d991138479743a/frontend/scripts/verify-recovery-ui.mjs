import { strict as assert } from "node:assert";
import { readFile } from "node:fs/promises";

const overview = await readFile(new URL("../src/pages/ProjectDetails.jsx", import.meta.url), "utf8");
const settings = await readFile(new URL("../src/pages/ProjectSettings.jsx", import.meta.url), "utf8");
const requirements = await readFile(new URL("../src/pages/DeploymentRequirements.jsx", import.meta.url), "utf8");
const pipeline = await readFile(new URL("../src/pages/ProjectPipeline.jsx", import.meta.url), "utf8");
const card = await readFile(new URL("../src/components/projects/DeploymentRecoveryCard.jsx", import.meta.url), "utf8");
const developerDetails = await readFile(new URL("../src/components/projects/DeveloperDetailsAccordion.jsx", import.meta.url), "utf8");
assert.equal((overview.match(/<DeploymentRecoveryCard/g) || []).length, 1);
assert.match(overview, /state\.recoveryIssue/);
assert.match(overview, /state\.currentRecoveryIssue/);
assert.match(overview, /previousDeploymentIssue/);
assert.match(overview, /Pending re-evaluation/);
assert.match(overview, /!showRecovery && state\.nextAction/);
assert.match(overview, /!showRecovery && state\.runControls\?\.canRetry/);
assert.doesNotMatch(overview, /isStateRecovery|isEcsFailure/);
assert.match(settings, /focusSection/);
assert.match(settings, /Show full settings/);
assert.match(settings, /requirementsFocus/);
assert.match(settings, /focusedDetection/);
assert.match(settings, /focusedHealth/);
assert.match(settings, /hasReachedHealthVerification/);
assert.match(settings, /deploymentContract\?\.healthPath/);
assert.doesNotMatch(settings, /placeholder="\/health"/);
assert.match(requirements, /focus !== "database"/);
assert.match(requirements, /focus !== "secrets"/);
assert.match(requirements, /Show all requirements/);
assert.match(card, /IssueEvidenceList/);
assert.match(card, /DeveloperDetailsAccordion/);
assert.match(card, /After the fix, DeployGuard can continue/);
assert.match(pipeline, /current\.recoveryIssue/);
assert.match(pipeline, /Approve infrastructure changes/);
assert.match(pipeline, /DeploymentRecoveryCard/);
assert.match(pipeline, /showResume/);
assert.doesNotMatch(pipeline, /isStateRecovery|isEcsFailure|function recoveryHref/);
assert.match(developerDetails, /useProductMode/);
assert.match(developerDetails, /!isDeveloperMode/);
console.log("Recovery overview and focused-settings UI verification passed.");
