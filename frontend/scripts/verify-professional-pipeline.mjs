import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const page = read("../src/pages/ProjectPipeline.jsx");
const execution = read("../src/components/projects/PipelineExecution.jsx");
const recovery = read("../src/components/projects/PipelineRecoveryPanel.jsx");
const styles = read("../src/styles.css");
const designSystem = read("../src/design-system.css");
const backend = read("../../backend/src/projects/railpack-deployment.service.ts");
const github = read("../../backend/src/projects/pipeline/github-actions.service.ts");
const stagePresentation = read("../../backend/src/projects/pipeline/github-actions-stage-presentation.ts");

assert.match(page, /getGithubActionsDeploymentHistory/);
assert.match(page, /PipelineExecution/);
assert.match(page, /PipelineRecoveryPanel operations=\{operations\}/);
assert.doesNotMatch(page, /CanonicalDeploymentView/);
assert.equal((execution.match(/<MetricCard/g) || []).length, 0, "Pipeline uses one compact deployment identity instead of repeated summary cards");
assert.match(execution, /className="pipeline-identity-card"/);
for (const heading of ["Latest deployment", "Operation", "Duration", "Completed"]) assert.match(execution, new RegExp(heading));
assert.doesNotMatch(execution, /\$\{date\(latest\.createdAt\)\} to \$\{date\(operationEnd\(latest\)\)\}/, "Pipeline omits the verbose start-to-end range");
assert.match(execution, /latest\?\.workflowStages \|\| \[\]/);
assert.match(execution, /stage\.durationMs/);
assert.match(execution, /stage\.status !== "skipped"[\s\S]*stage\.durationMs > 0/);
assert.match(execution, /stage\.status === "skipped" \? "Not run"/);
assert.match(execution, /function stageDurationLabel/);
assert.match(execution, /ChartCard/);
assert.match(execution, /timedStages\.length \? <ChartCard/, "empty duration charts are omitted");
assert.match(execution, /GitHub Actions stage durations/);
for (const heading of ["Attempt", "Type", "Result", "Commit", "Duration", "Time"]) assert.match(execution, new RegExp(`<th>${heading}<`));
assert.match(execution, /retryOfOperationId/);
assert.match(execution, /retryGithubActionsDeployment\(projectId\)/);
assert.match(execution, /currentState\.canRetry/);
assert.doesNotMatch(execution, /Redeploy|destroyGithubActionsDeployment|deployGithubActionsDeployment|CPU|memory|request chart|error chart/i);
assert.match(execution, /Advanced run details/);
assert.match(execution, /workflowRunId/);
assert.match(recovery, /Sanitized failure evidence/);
assert.match(recovery, /startTroubleshooting/);
assert.match(recovery, /operation\.aiAnalysisEligible/);
assert.match(recovery, /AI troubleshooting requires a failed deployment attempt with sanitized persisted evidence/);
assert.doesNotMatch(recovery, /CloudWatch|Redis|BullMQ/);
assert.match(backend, /workflowStages: Array\.isArray\(metadata\.workflowStages\)/);
assert.match(github, /getWorkflowJobs/);
assert.match(backend, /failureSource: "github_actions"/);
assert.match(backend, /getWorkflowStages/);
assert.match(github, /started_at\?: string \| null/);
assert.match(github, /completed_at\?: string \| null/);
for (const stage of ["checkout_exact_application_source", "configure_aws_credentials_through_oidc", "build_immutable_railpack_image", "publish_immutable_image_to_ecr", "materialize_release_runtime"]) assert.match(stagePresentation, new RegExp(stage));
for (const selector of ["pipeline-stage-timeline", "pipeline-duration-chart", "pipeline-history-card"]) assert.match(styles, new RegExp(selector));
assert.match(designSystem, /\.pipeline-identity-card/);
assert.equal((recovery.match(/<h2>Deployment attempts<\/h2>/g) || []).length, 0, "Recovery does not create a competing deployment-history heading");
console.log("Professional GitHub Actions Pipeline and Recovery presentation verification passed.");
