import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";
import { pipelineStageDisplayStatus, pipelineStageDurationEnd } from "../src/utils/pipelineStageTiming.js";

const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const page = read("../src/pages/ProjectPipeline.jsx");
const execution = read("../src/components/projects/PipelineExecution.jsx");
const graph = read("../src/components/projects/PipelineGraph.jsx");
const styles = read("../src/styles/pages/deployments.css");
const backend = read("../../backend/src/projects/railpack-deployment.service.ts");
const github = read("../../backend/src/projects/pipeline/github-actions.service.ts");
const stagePresentation = read("../../backend/src/projects/pipeline/github-actions-stage-presentation.ts");

assert.match(page, /getGithubActionsDeploymentHistory/);
assert.match(page, /PipelineExecution/);
assert.doesNotMatch(page, /PipelineRecoveryPanel/, "failures are explained once, on Troubleshoot");
assert.doesNotMatch(page, /CanonicalDeploymentView/);
assert.doesNotMatch(execution, /MetricCard/, "one compact identity for the latest attempt instead of summary cards");
assert.match(execution, /className="panel latest-run"/);
assert.match(execution, /operationTypeLabel\(latest\)\} · attempt \{latest\.attempt\}/);
assert.match(execution, /latest\?\.workflowStages \|\| \[\]/);
assert.match(execution, /pipelineStageDurationEnd\(stage, operation\)/);
assert.match(execution, /workflowStagesUnavailable \? "Step details are temporarily unavailable from GitHub Actions/, "missing terminal jobs metadata is presented honestly");
assert.match(execution, /stage\.status === "skipped"\) return "Skipped"/);
assert.match(execution, /displayStatus === "unavailable"\) return "Not recorded"/, "stale stage timing is never invented");
assert.match(execution, /function stageDurationLabel/);
assert.doesNotMatch(execution, /ChartCard|timedStages/, "timing is shown with each stage, not duplicated in a chart");
for (const heading of ["Result", "Type", "Attempt", "Commit", "Started", "Duration"]) assert.match(execution, new RegExp(`<th>${heading}<`));
assert.match(execution, /retryOfOperationId/);
assert.doesNotMatch(execution, /Redeploy|destroyGithubActionsDeployment|retryGithubActionsDeployment|CPU|memory|request chart|error chart/i, "Deployments records attempts; it starts nothing");
assert.match(execution, /Run identifiers/);
assert.match(execution, /workflowRunId/);
assert.match(graph, /\["failed", "running"\]\.includes\(phase\.status\)/, "phases with a failure or a running step open by default");
assert.match(graph, /stage\.failureReason \? <pre className="code stage-failure">/, "a failed step shows its reason in place");
assert.match(graph, /aria-expanded=\{open\}/);
assert.match(backend, /workflowStages: Array\.isArray\(metadata\.workflowStages\)/);

const staleRunningStage = { status: "running", startedAt: "2026-09-01T10:00:00.000Z", completedAt: null };
assert.equal(pipelineStageDurationEnd(staleRunningStage, { status: "completed", completedAt: "2026-09-01T10:05:00.000Z" }, "2026-09-02T10:00:00.000Z"), "2026-09-01T10:05:00.000Z", "terminal operations cap stale running-stage duration at the operation terminal timestamp");
assert.equal(pipelineStageDurationEnd(staleRunningStage, { status: "failed", failedAt: "2026-09-01T10:04:00.000Z" }, "2026-09-02T10:00:00.000Z"), "2026-09-01T10:04:00.000Z");
assert.equal(pipelineStageDurationEnd(staleRunningStage, { status: "completed" }, "2026-09-02T10:00:00.000Z"), null, "missing terminal timestamps never fall through to the current clock");
assert.equal(pipelineStageDurationEnd(staleRunningStage, { status: "running" }, "2026-09-02T10:00:00.000Z"), "2026-09-02T10:00:00.000Z", "active operations continue to accumulate duration");
assert.equal(pipelineStageDisplayStatus(staleRunningStage, { status: "completed" }), "unavailable", "a terminal operation never presents stale stage metadata as actively Running");
assert.equal(pipelineStageDisplayStatus(staleRunningStage, { status: "failed" }), "unavailable");
assert.equal(pipelineStageDisplayStatus({ status: "pending" }, { status: "completed" }), "unavailable", "a terminal operation never presents stale stage metadata as Pending");
assert.equal(pipelineStageDisplayStatus({ status: "pending" }, { status: "failed" }), "unavailable");
assert.equal(pipelineStageDisplayStatus(staleRunningStage, { status: "running" }), "running");
assert.equal(pipelineStageDisplayStatus({ status: "passed" }, { status: "completed" }), "passed", "the guard never manufactures successful GitHub evidence");
assert.match(github, /getWorkflowJobs/);
assert.match(backend, /failureSource: "github_actions"/);
assert.match(backend, /getWorkflowStages/);
assert.match(github, /started_at\?: string \| null/);
assert.match(github, /completed_at\?: string \| null/);
for (const stage of ["checkout_exact_application_source", "configure_aws_credentials_through_oidc", "build_immutable_railpack_image", "publish_immutable_image_to_ecr", "materialize_release_runtime"]) assert.match(stagePresentation, new RegExp(stage));
for (const selector of ["stage-list", "stage-step", "latest-run"]) assert.match(styles, new RegExp(selector));
console.log("Professional GitHub Actions Pipeline and Recovery presentation verification passed.");
