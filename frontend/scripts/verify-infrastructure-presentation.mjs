import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const page = read("../src/pages/ProjectInfrastructure.jsx");
const styles = read("../src/styles.css");
const routes = read("../src/routes/AppRoutes.jsx");

assert.match(routes, /path="\/projects\/:projectId\/infrastructure"/);
assert.doesNotMatch(page, /<dl[\s>]/, "Infrastructure must not use raw definition-list presentation.");
for (const summary of ["Application", "ECS", "Load balancer", "Region"]) assert.match(page, new RegExp(`label="${summary}"`));
assert.equal((page.match(/<MetricCard/g) || []).length, 6, "Infrastructure has four health cards and two persisted pricing cards.");
assert.match(page, /Technical details/);
for (const heading of ["Resource", "Identifier"]) assert.match(page, new RegExp(`<th>${heading}<`));
assert.match(page, /<CopyValue/);
assert.match(page, /label="Copy full identifier"/);
assert.match(page, /function shortened/);
assert.match(page, /Service flow/);
for (const node of ["Source", "Build", "ECR", "ECS", "ALB", "Application"]) assert.match(page, new RegExp(node));
for (const supporting of ["Terraform", "CloudWatch", "Infracost"]) assert.match(page, new RegExp(supporting));
assert.match(page, /current LIVE release has no persisted Infracost evidence/i);
assert.match(page, /Pricing unavailable/);
assert.match(page, /cost\?\.source === "infracost"/);
assert.match(page, /Service breakdown/);
const currentState = read("../../backend/src/projects/current-state/project-current-state.service.ts");
assert.match(currentState, /failedDestroy[\s\S]*runtimeObservation\(project, route\.liveGenerationId, projectedWithCanonicalRuntime\.stableUrl!\)/, "a failed Destroy must reconcile one bounded runtime observation before presenting historical release data as LIVE");
assert.match(currentState, /runtimeUnverifiedAfterDestroy[\s\S]*stableRelease: null[\s\S]*stableUrl: null/, "an absent or unverified runtime after Destroy must remove historical LIVE authority");
assert.ok(currentState.includes("endpoint: /^https?:\\/\\//i.test(stableUrl) ? stableUrl : null"), "the application link must use the verified project host route, never the shared ALB default URL");
assert.match(currentState, /lastApplyAt: authoritativeLiveRelease \? liveReleaseObservedAt : null/, "a failed Destroy must not be presented as a newer Terraform apply");
assert.match(page, /subscribeProjectStateChanged/);
assert.match(page, /Destroy cleanup required/);
assert.match(page, /Retry Failed Destroy/);
assert.match(page, /evidence\?\.cloudWatch\?\.status/);
for (const selector of ["infrastructure-summary-grid", "infrastructure-inventory-card", "infrastructure-topology", "infrastructure-finops-card", "infrastructure-support-grid"]) assert.match(styles, new RegExp(selector));
assert.match(styles, /@media\(max-width:560px\)[\s\S]*infrastructure-summary-grid/);
assert.match(styles, /\.infrastructure-inventory-card \.ds-data-table\{min-width:760px\}/);
console.log("Infrastructure and FinOps presentation verification passed.");
