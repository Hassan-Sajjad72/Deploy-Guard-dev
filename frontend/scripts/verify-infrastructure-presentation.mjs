import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const page = read("../src/pages/ProjectInfrastructure.jsx");
const styles = read("../src/styles.css");
const routes = read("../src/routes/AppRoutes.jsx");
const exportService = read("../../backend/src/terraform-export/terraform-export.service.ts");

assert.match(routes, /path="\/projects\/:projectId\/infrastructure"/);
assert.doesNotMatch(page, /<dl[\s>]/, "Infrastructure must not use raw definition-list presentation.");
assert.match(page, /<MetricCard[\s\S]*Infrastructure state/);
assert.match(page, /<MetricCard[\s\S]*AWS region/);
assert.match(page, /<MetricCard[\s\S]*ECS task state/);
assert.match(page, /<MetricCard[\s\S]*ALB health/);
assert.equal((page.match(/<MetricCard/g) || []).length, 7, "Infrastructure has four summary cards and three authoritative cost/release cards.");
assert.match(page, /Resource inventory/);
for (const heading of ["Resource", "Identifier", "Status", "Details"]) assert.match(page, new RegExp(`<th>${heading}<`));
assert.match(page, /<CopyValue/);
assert.match(page, /label="Copy full identifier"/);
assert.match(page, /function shortened/);
assert.match(page, /Deployment topology/);
for (const node of ["GitHub Actions", "ECR", "ECS Fargate", "Application Load Balancer", "Application"]) assert.match(page, new RegExp(node));
assert.match(page, /No verified Infracost estimate exists for the authoritative LIVE release\./);
assert.match(page, /Cost estimate unavailable/);
assert.match(page, /cost\?\.source === "infracost"/);
assert.match(page, /Estimated monthly cost by service/);
assert.match(page, /historical \? "Historical"/);
assert.match(page, /No live endpoint or active resource is claimed/);
assert.match(page, /The previous verified release is still live/);
assert.match(page, /authority\?\.infrastructure\?\.status \|\| "unknown"/, "Infrastructure page status must describe infrastructure rather than the latest failed operation");
const currentState = read("../../backend/src/projects/current-state/project-current-state.service.ts");
assert.match(currentState, /options\.refreshCloudState && hasAuthoritativeLiveRelease && route\?\.liveGenerationId[\s\S]*liveAwsEvidence\(project, route\.liveGenerationId, projectedWithCost\.stableUrl!\)/, "ordinary project reads must not wait for live AWS inspection");
assert.ok(currentState.includes("endpoint: /^https?:\\/\\//i.test(stableUrl) ? stableUrl : null"), "the application link must use the verified project host route, never the shared ALB default URL");
assert.match(currentState, /lastApplyAt: authoritativeLiveRelease \? liveReleaseObservedAt : null/, "a failed Destroy must not be presented as a newer Terraform apply");
assert.match(page, /Export Terraform ZIP/);
assert.match(page, /subscribeProjectStateChanged/);
assert.match(exportService, /contains no state, plan, credentials, or real tfvars values/);
for (const selector of ["infrastructure-summary-grid", "infrastructure-inventory-card", "infrastructure-topology", "infrastructure-finops-card", "infrastructure-export-card"]) assert.match(styles, new RegExp(selector));
assert.match(styles, /@media\(max-width:560px\)[\s\S]*infrastructure-summary-grid/);
assert.match(styles, /\.infrastructure-inventory-card \.ds-data-table\{min-width:760px\}/);
console.log("Infrastructure and FinOps presentation verification passed.");
