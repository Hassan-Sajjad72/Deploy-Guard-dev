import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";

const routes = readFileSync(new URL("../src/routes/AppRoutes.jsx", import.meta.url), "utf8");
const landing = readFileSync(new URL("../src/pages/Landing.jsx", import.meta.url), "utf8");
const publicHeader = readFileSync(new URL("../src/components/layout/PublicHeader.jsx", import.meta.url), "utf8");
const projects = readFileSync(new URL("../src/pages/Projects.jsx", import.meta.url), "utf8");
const authApi = readFileSync(new URL("../src/api/authApi.js", import.meta.url), "utf8");
const authContext = readFileSync(new URL("../src/context/AuthContext.jsx", import.meta.url), "utf8");
const githubConnecting = readFileSync(new URL("../src/pages/GithubConnecting.jsx", import.meta.url), "utf8");
const header = readFileSync(new URL("../src/components/layout/AppHeader.jsx", import.meta.url), "utf8");

for (const route of ["/login", "/signup"]) assert.match(routes, new RegExp(`<Route element=\\{<Navigate replace to="/" \\/>\\} path="${route.replaceAll("/", "\\/")}"`));
assert.match(routes, /<Route element=\{<Navigate replace to="\/projects" \/>\} path="\/dashboard"/, "historical /dashboard links land on the workspace home");
assert.match(header, /label: "Projects", to: "\/projects"/);
assert.match(projects, /getWorkspaceSummary/);
assert.match(projects, /needsAttention/, "the workspace home folds attention into the single project list");
assert.match(projects, /\["ATTENTION", "Needs attention"\]/);
assert.match(projects, /rank = attention \? 0 : presentation\.active \? 1 : 2/, "attention, then active, then the rest");
assert.match(projects, /conciseProjectSummary/);
assert.match(projects, /normalReleaseView/);
assert.doesNotMatch(projects, /FleetGauge|dg-home-fleet|dg-home-kpis|Recently used projects/, "the home stays a list, not a dashboard of widgets");
assert.match(routes, /path="\/deploy"/);
assert.match(routes, /<Route element=\{<Navigate replace to="\/deploy" \/>\} path="\/projects\/new"/);
assert.match(landing, /data-home-deploy="oauth"/);
assert.match(landing, /data-home-deploy="authenticated"/);
assert.match(landing, />Continue with GitHub<\/Link>/);
assert.match(landing, /Connect a GitHub repository and DeployGuard runs it on AWS/);
assert.equal((landing.match(/data-home-deploy=/g) || []).length, 2, "The two auth branches must define one primary CTA each, never render together.");
assert.doesNotMatch(publicHeader, /to="\/dashboard"/, "signed-in visitors get one way back to their projects");
assert.match(publicHeader, /to="\/projects">Open projects<\/Link>/);
assert.match(publicHeader, /aria-label="Public navigation"/);
assert.match(landing, /<PublicHeader \/>/);
assert.match(publicHeader, /to="\/about">About<\/NavLink>/);
assert.doesNotMatch(landing, />Founders<|>How we build</);
assert.match(landing, /const cta = isAuthenticated/);
assert.match(publicHeader, /to="\/admin\/login">Admin<\/NavLink>/);
assert.match(landing, /<DeployGuardArchitecture \/>/);
assert.match(landing, /<PublicFooter \/>/);
assert.doesNotMatch(landing, /pathname: "\/admin"[\s\S]*to="\/auth\/github"/);
assert.doesNotMatch(landing, /role === "admin"/);
assert.match(landing, /state=\{\{ from: \{ pathname: "\/deploy" \} \}\}/);
assert.doesNotMatch(landing, /summary>Account<\/summary>|landing-feature-grid|landing-flow/);
assert.doesNotMatch(landing, />\s*(?:Use email|Sign up|Log in)\s*</i);
assert.doesNotMatch(authApi, /signupUser|loginUser|\/api\/auth\/(?:signup|login)/);
assert.doesNotMatch(authContext, /\blogin\b|\bsignup\b/);
assert.doesNotMatch(githubConnecting, /to="\/login"/);
assert.match(githubConnecting, /: "\/deploy"/);
assert.match(githubConnecting, /Signing in does not change your GitHub account, repositories or settings/);
assert.match(githubConnecting, /Nothing about your GitHub or DeployGuard account was changed/);
assert.match(authContext, /window\.addEventListener\("focus", refreshOnReturn\)/);
assert.match(authContext, /document\.addEventListener\("visibilitychange", refreshOnReturn\)/);
assert.match(projects, /Search by name, repository or branch/);
assert.match(projects, /stateFilter === "ALL" \|\| \(stateFilter === "ATTENTION"/);
assert.match(projects, /\["DESTROYED", "Destroyed"\]/);
assert.match(projects, /projects-list/);
assert.doesNotMatch(projects, /Latest deployment|<span>Services<\/span>/, "Projects is a concise registry, not a deployment dashboard.");
assert.match(projects, /<Time value=\{activity\} \/>/);
assert.doesNotMatch(projects, /project-trust-table/);
assert.match(projects, /to="\/deploy"/);
assert.match(projects, /`\/projects\/\$\{project\.id\}`/);

console.log("GitHub-first workspace home verification passed.");
