import { strict as assert } from "node:assert";
import { readFileSync } from "node:fs";

const routes = readFileSync(new URL("../src/routes/AppRoutes.jsx", import.meta.url), "utf8");
const landing = readFileSync(new URL("../src/pages/Landing.jsx", import.meta.url), "utf8");
const projects = readFileSync(new URL("../src/pages/Projects.jsx", import.meta.url), "utf8");
const authApi = readFileSync(new URL("../src/api/authApi.js", import.meta.url), "utf8");
const authContext = readFileSync(new URL("../src/context/AuthContext.jsx", import.meta.url), "utf8");
const githubConnecting = readFileSync(new URL("../src/pages/GithubConnecting.jsx", import.meta.url), "utf8");
const dashboard = readFileSync(new URL("../src/pages/Dashboard.jsx", import.meta.url), "utf8");
const sidebar = readFileSync(new URL("../src/components/layout/Sidebar.jsx", import.meta.url), "utf8");

for (const route of ["/login", "/signup"]) assert.match(routes, new RegExp(`<Route element=\\{<Navigate replace to="/" \\/>\\} path="${route.replaceAll("/", "\\/")}"`));
assert.match(routes, /<Route element=\{<Dashboard \/>\} path="\/dashboard"/);
assert.match(sidebar, /label: "Home", to: "\/dashboard"/);
assert.match(dashboard, /getWorkspaceSummary/);
for (const section of ["Needs attention", "Active deployments", "Recent activity", "Recently used projects"]) assert.match(dashboard, new RegExp(section));
assert.match(dashboard, /<h1>Home<\/h1>/);
assert.match(dashboard, /No deployment attempts yet/);
assert.match(dashboard, /<span>Live<\/span>/);
assert.doesNotMatch(dashboard, /view\.stable\.length|continue-deployment-card|Live projects/);
assert.match(dashboard, /view\.active\.length/);
assert.doesNotMatch(dashboard, /<h1>Deployments<\/h1>|Worked on|releaseSummary/);
assert.match(routes, /path="\/deploy"/);
assert.match(routes, /<Route element=\{<Navigate replace to="\/deploy" \/>\} path="\/projects\/new"/);
assert.match(landing, /data-home-deploy="oauth"/);
assert.match(landing, /data-home-deploy="authenticated"/);
assert.match(landing, />Continue with GitHub<\/Link>/);
assert.match(landing, /Connect your repo\. DeployGuard takes it from code to secure, running cloud infrastructure\./);
assert.equal((landing.match(/data-home-deploy=/g) || []).length, 2, "The two auth branches must define one primary CTA each, never render together.");
assert.match(landing, /<details className="landing-account-menu">/);
assert.match(landing, /<Link to="\/dashboard">Dashboard<\/Link>/);
assert.match(landing, /<Link to="\/projects">Projects<\/Link>/);
assert.match(landing, /aria-label="Public navigation"/);
assert.match(landing, /to="\/about">About us<\/Link>/);
assert.doesNotMatch(landing, />Founders<|>How we build</);
assert.match(landing, /\{isAuthenticated \? \(/);
assert.match(landing, /<PublicAdminLink \/>/);
assert.match(landing, /<DeployGuardArchitecture \/>/);
assert.match(landing, /<PublicFooter \/>/);
assert.doesNotMatch(landing, /pathname: "\/admin"[\s\S]*to="\/auth\/github"/);
assert.doesNotMatch(landing, /role === "admin"/);
assert.match(landing, /state=\{\{ from: \{ pathname: "\/deploy" \} \}\}/);
assert.doesNotMatch(landing, /summary>Account<\/summary>|landing-feature-grid|landing-flow/);
assert.doesNotMatch(landing, />\s*(?:Use email|Sign up|Log in)\s*</i);
assert.doesNotMatch(authApi, /signupUser|loginUser|\/api\/auth\/(?:signup|login)/);
assert.doesNotMatch(authContext, /\blogin\b|\bsignup\b/);
assert.doesNotMatch(githubConnecting, /to="\/login"/);
assert.match(githubConnecting, /: "\/deploy"/);
assert.match(projects, /Search projects, repositories, or branches/);
assert.match(projects, /stateFilter === "ALL" \|\| projectStatePresentation/);
assert.match(projects, /\["DESTROYED", "Destroyed"\]/);
assert.match(projects, /project-card-grid/);
assert.match(projects, /Latest deployment/);
assert.match(projects, /<span>Services<\/span>/);
assert.match(projects, /Last activity/);
assert.doesNotMatch(projects, /project-trust-table/);
assert.match(projects, /to="\/deploy"/);
assert.match(projects, /to=\{`\/projects\/\$\{project\.id\}`\}/);

console.log("GitHub-first Home verification passed.");
