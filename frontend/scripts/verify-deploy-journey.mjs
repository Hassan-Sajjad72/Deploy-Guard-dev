import { strict as assert } from "node:assert";
import { readFile } from "node:fs/promises";
import { parseEnvPaste } from "../src/utils/envPaste.js";
import { createDeploymentSelectionGate, deploymentSelectionKey } from "../src/utils/deploymentSelection.js";

const parsed = parseEnvPaste("# application settings\nAPI_URL=https://example.test\nTOKEN=quoted value\n\n");
assert.deepEqual(parsed.errors, [], "comments and blank lines are accepted");
assert.deepEqual(parsed.entries.map(({ key }) => key), ["API_URL", "TOKEN"], "only names are retained for the journey");
assert.equal(parsed.entries[1].isSecret, true, "secret-like names are marked for encrypted persistence");
assert.match(parseEnvPaste("API_URL=x\nAPI_URL=y").errors[0], /Line 2: API_URL is duplicated/);
assert.match(parseEnvPaste("not an assignment").errors[0], /Line 1: use KEY=value/);
const managed = parseEnvPaste("PORT=3000\nAWS_ACCESS_KEY_ID=secret-value\nGITHUB_TOKEN=token-value\nACTIONS_RUNTIME_TOKEN=actions-value\nTF_VAR_REGION=region-value\nDEPLOYGUARD_PROJECT_ID=id-value\nJWT_SECRET=app-value");
assert.deepEqual(managed.errors, [], "platform-managed variables do not block valid application variables");
assert.deepEqual(managed.entries.map(({ key }) => key), ["JWT_SECRET"]);
assert.deepEqual(managed.ignoredVariableNames, ["ACTIONS_RUNTIME_TOKEN", "AWS_ACCESS_KEY_ID", "DEPLOYGUARD_PROJECT_ID", "GITHUB_TOKEN", "PORT", "TF_VAR_REGION"]);
assert.doesNotMatch(JSON.stringify(managed), /secret-value|token-value|actions-value|region-value|id-value|3000/, "ignored values are discarded at parse time");
assert.match(managed.warnings.join(" "), /PORT is managed by DeployGuard and was ignored/);
assert.equal(parseEnvPaste("").entries.length, 0, "an empty .env block is accepted");
const externalDatabase = parseEnvPaste("DATABASE_URL=postgresql://external.example/app");
assert.equal(externalDatabase.entries[0].isSecret, true, "external database URLs retain encrypted secret delivery");

const gate = createDeploymentSelectionGate();
const branchA = gate.begin("Example/Application", "main");
gate.select("Example/Application", "master");
const branchB = gate.begin("Example/Application", "master");
assert.equal(gate.isCurrent(branchA), false, "a stale main response cannot overwrite master");
assert.equal(gate.isCurrent(branchB), true, "the current master response is accepted");
gate.select("Another/Repository", "main");
assert.equal(gate.isCurrent(branchB), false, "changing repository invalidates previous readiness");
const repeated = gate.begin("Another/Repository", "main");
assert.equal(gate.isCurrent(repeated), true, "same-branch review can safely become the current request");
assert.equal(deploymentSelectionKey("Example/Application", "master"), "example/application:master");

const page = await readFile(new URL("../src/pages/NewProject.jsx", import.meta.url), "utf8");
assert.match(page, /getGithubRepositories/);
assert.match(page, /connectGithubAppInstallation/);
assert.match(page, /inspectGithubRepository/);
assert.match(page, /parseEnvPaste/);
assert.match(page, /updateProjectBranch\(project\.id, requestedBranch\)/, "an existing project is aligned to the selected branch before deployment");
assert.doesNotMatch(page, /runStackDetection|generatePreflightReport|Detector|Legacy mode|Detect Stack/);
assert.match(page, /<ReadinessSummary/);
assert.match(page, /<IssueCard/);
assert.match(page, /Review readiness/);
assert.match(page, /function deploymentJourney/);
assert.match(page, /aria-label="Deployment readiness journey"/);
assert.match(page, /<span>Application Port<\/span>/);
assert.match(page, /servicePort: Number\(servicePort\)/);
assert.match(page, /No managed database \/ use existing ENV/);
assert.match(page, /Database configuration conflict/);
assert.match(page, /MANAGED_DATABASE_ALIASES\[database\.engine\]/);
for (const step of ["Repository", "Branch", "Environment", "Deploy"]) assert.match(page, new RegExp(`label: "${step}"`));
assert.match(page, /hasReadiness \? "complete"/);
assert.match(page, /values are not displayed/);
assert.match(page, /deployGithubActionsDeployment\(readiness\.project\.id\)/, "one canonical Deploy action dispatches only after the repository and optional environment are saved");
assert.match(page, /navigate\(`\/projects\/\$\{readiness\.project\.id\}`\)/, "the journey redirects to the canonical Project page");
assert.doesNotMatch(page, /archiveProject|createProjectEnvVar|Repository URL/);
assert.doesNotMatch(page, /\/requirements/);
assert.doesNotMatch(page, /savedKeys\.join/);
console.log("Single-page deployment journey parser and surface verification passed");
