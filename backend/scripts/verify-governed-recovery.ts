async function sandbox() {
  const pinned = `registry.example/approved-repair@sha256:${"a".repeat(64)}`;
  const args = repairSandboxArguments("/tmp/bounded-source", pinned, ["node", "tests/defect.js"], "fixture");
  for (const protection of ["none", "--read-only", "ALL", "no-new-privileges", "65534:65534", "64", "512m", "never"]) assert.ok(args.includes(protection));
  assert.ok(args.includes("type=bind,source=/tmp/bounded-source,target=/source,readonly"));
  assert.throws(() => repairSandboxArguments("/tmp/source", "node:latest", ["node", "test.js"], "fixture"));
  let invocations: any[] = [];
  const runner = async (...input: any[]) => { invocations.push(input); if (input[1][0] === "run") throw Object.assign(new Error("fixture failing assertion"), { code: 1 }); return { stdout: "", stderr: "" }; };
  assert.equal((await runRepairSandbox("/tmp/source", pinned, ["node", "test.js"], runner as any)).status, "FAILED");
  assert.equal(invocations.length, 2); assert.equal(invocations[1][1][0], "rm");
  assert.deepEqual(Object.keys(invocations[0][2].env), ["PATH"]);
  invocations = [];
  const absent = async (...input: any[]) => { invocations.push(input); throw Object.assign(new Error("docker missing"), { code: "ENOENT" }); };
  assert.equal((await runRepairSandbox("/tmp/source", pinned, ["node", "test.js"], absent as any)).status, "UNVERIFIED");
  console.log("Focused repair sandbox boundary checks passed.");
}
sandbox().catch((error) => { console.error(error); process.exitCode = 1; });
